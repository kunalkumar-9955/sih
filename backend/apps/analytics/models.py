"""
SIH26002 — Explainable AI Decision & Command Center Analytics Models.

Provides models for centralizing decision explanations, auditability,
and time-series network health snapshots.
"""
from django.conf import settings
from django.db import models

from apps.core.models import BaseModel


class DecisionRecommendation(BaseModel):
    """
    Centralized explainable decision record for all AI and optimization outputs.
    Stores recommendation details, confidence, primary driving factors,
    trade-offs, model/version metadata, and human operator override tracking.
    """
    class DecisionType(models.TextChoices):
        ROUTE_RECOMMENDATION = "ROUTE_RECOMMENDATION", "Route Recommendation"
        REROUTE_RECOMMENDATION = "REROUTE_RECOMMENDATION", "In-Transit Reroute"
        FLEET_ASSIGNMENT = "FLEET_ASSIGNMENT", "Fleet Vehicle Assignment"
        LOAD_CONSOLIDATION = "LOAD_CONSOLIDATION", "Load Consolidation"
        ETA_PREDICTION = "ETA_PREDICTION", "ETA & Delay Prediction"
        ACCESSIBILITY_INTERVENTION = "ACCESSIBILITY_INTERVENTION", "Corridor Accessibility Recovery"
        DISASTER_ESCALATION = "DISASTER_ESCALATION", "Disaster Mode Escalation"

    class RecommendationStatus(models.TextChoices):
        GENERATED = "GENERATED", "Generated by AI Engine"
        ACCEPTED = "ACCEPTED", "Accepted by Operator / Driver"
        OVERRIDDEN = "OVERRIDDEN", "Overridden by Operator"
        REJECTED = "REJECTED", "Rejected by System / Constraint"

    decision_type = models.CharField(
        max_length=40,
        choices=DecisionType.choices,
        db_index=True,
    )
    title = models.CharField(max_length=200)
    target_entity_type = models.CharField(max_length=50)  # Route, Trip, Vehicle, FreightLoad, Corridor
    target_entity_id = models.CharField(max_length=64, db_index=True)

    recommendation_payload = models.JSONField(
        default=dict,
        help_text="Actionable recommendation payload.",
    )
    confidence = models.FloatField(default=0.85, help_text="AI model confidence score [0.0 - 1.0].")

    primary_factors = models.JSONField(
        default=list,
        blank=True,
        help_text="Key factors influencing the decision with impact weights.",
    )
    tradeoffs = models.JSONField(
        default=list,
        blank=True,
        help_text="Comparative trade-offs (e.g. +12 min time vs -45% hazard).",
    )

    algorithm_version = models.CharField(max_length=64, default="explain-ai-v1")
    is_simulation = models.BooleanField(default=False)

    status = models.CharField(
        max_length=20,
        choices=RecommendationStatus.choices,
        default=RecommendationStatus.GENERATED,
        db_index=True,
    )
    operator_override_reason = models.TextField(blank=True)
    operator = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="reviewed_decisions",
    )

    class Meta:
        db_table = "analytics_decision_recommendation"
        ordering = ["-created_at"]
        indexes = [
            models.Index(fields=["decision_type", "status"]),
            models.Index(fields=["target_entity_type", "target_entity_id"]),
        ]

    def __str__(self) -> str:
        return f"Decision [{self.decision_type}]: {self.title} ({self.confidence*100:.0f}% conf)"


class NetworkHealthSnapshot(BaseModel):
    """
    Time-series snapshot of network operational health metrics for the Command Center.
    """
    class SeverityState(models.TextChoices):
        NORMAL = "NORMAL", "Normal Operations"
        WATCH = "WATCH", "Elevated Hazard Watch"
        WARNING = "WARNING", "Corridor Warning / Disruption"
        CRITICAL = "CRITICAL", "Critical Infrastructure Emergency"

    severity_state = models.CharField(
        max_length=20,
        choices=SeverityState.choices,
        default=SeverityState.NORMAL,
        db_index=True,
    )

    active_trips_count = models.PositiveIntegerField(default=0)
    delayed_shipments_count = models.PositiveIntegerField(default=0)
    active_hazards_count = models.PositiveIntegerField(default=0)
    critical_corridors_count = models.PositiveIntegerField(default=0)

    fleet_utilization_pct = models.FloatField(default=0.0)
    unassigned_freight_count = models.PositiveIntegerField(default=0)

    overall_accessibility_index = models.FloatField(
        default=100.0,
        help_text="Composite regional accessibility score 0-100.",
    )
    multimodal_terminal_status = models.JSONField(
        default=dict,
        blank=True,
        help_text="Status summary of major ports and rail sidings.",
    )

    critical_alerts = models.JSONField(
        default=list,
        blank=True,
        help_text="Active high-priority incidents and warnings.",
    )

    class Meta:
        db_table = "analytics_network_health_snapshot"
        ordering = ["-created_at"]
        indexes = [
            models.Index(fields=["severity_state", "-created_at"]),
        ]

    def __str__(self) -> str:
        return f"Health [{self.severity_state}] at {self.created_at}: Access={self.overall_accessibility_index:.1f}"
